/**
 * Resolves any icon name or emoji to a crisp vector Lucide icon component.
 * Case-insensitive lookup in dynamic icon catalog and emoji conversion map.
 */
export function getVectorIcon(iconOrEmoji?: string, fallback: React.ComponentType<any> = FileText): React.ComponentType<any> {
  if (!iconOrEmoji) return fallback;
  const trimmed = String(iconOrEmoji).trim();

  // 1. Check exact emoji mapping
  if (EMOJI_TO_VECTOR_MAP[trimmed]) {
    return EMOJI_TO_VECTOR_MAP[trimmed];
  }

  // 2. Check exact named icon
  if (DYNAMIC_ICONS[trimmed]) {
    return DYNAMIC_ICONS[trimmed];
  }

  // 3. Case-insensitive named icon lookup
  const lower = trimmed.toLowerCase();
  for (const [key, icon] of Object.entries(DYNAMIC_ICONS)) {
    if (key.toLowerCase() === lower) {
      return icon;
    }
  }

  return fallback;
}

export function resolveDynamicIcon(name?: string, fallback: React.ComponentType<any> = Type): React.ComponentType<any> {
  if (!name) return fallback;
  return getVectorIcon(name, fallback);
}
